import ollama
import pandas as pd
import re
import subprocess
import time

# Regex pattern for extracting answer letters
ANSWER_PATTERN = re.compile(r'\b([ABCD])\b', re.IGNORECASE | re.UNICODE)

# System prompt for the LLM
SYSTEM_MESSAGE = """Ти — об'єктивний асистент.
Твоє завдання — відповідати на тестові питання, обираючи лише одну правильну літеру (A, B, C або D).
Не пиши нічого іншого, крім цієї літери."""

# Input CSV (questions.csv) required columns
INPUT_CSV_REQUIRED_COLUMNS = [
    'ID',              # Question identifier
    'Question',        # The question text
    'Choice A',        # First answer choice
    'Choice B',        # Second answer choice
    'Choice C',        # Third answer choice
    'Choice D',        # Fourth answer choice
    'Correct Answer',  # The correct answer (A, B, C, or D)
    'Topic',           # Question category/topic
    'Time period',     # Historical time period of the question
    'Subject'          # Subject category for custom questions
]

# Output CSV ({model_name}_results.csv) structure
# Generated by run_benchmark() and saved in test modules
OUTPUT_CSV_COLUMNS = {
    'id': 'Question identifier from input CSV',
    'model': 'Name of the LLM model used for this test',
    'category': 'Question category/topic from input CSV',
    'raw_response': 'Raw text response from the model',
    'thinking': 'Model thinking process (if available, otherwise N/A)',
    'predicted': 'Predicted answer extracted from response (A, B, C, D, or N/A)',
    'actual': 'Correct answer from input CSV',
    'is_correct': 'Boolean (True/False) indicating if prediction matches actual answer'
}

# Default models to test
DEFAULT_MODELS = ['gemma3:4b', 'lapa-v0.1.2-q4', 'mamay-9b-q4', 'mamay-4b-q4']


def validate_input_csv(df):
    print(df.columns)
    """Validates that input CSV has all required columns."""
    missing_cols = [col for col in INPUT_CSV_REQUIRED_COLUMNS if col not in df.columns]
    if missing_cols:
        raise ValueError(
            f"Input CSV is missing required columns: {missing_cols}\n"
            f"Required columns: {INPUT_CSV_REQUIRED_COLUMNS}"
        )
    print(f"✓ Input CSV validation passed. Found all {len(INPUT_CSV_REQUIRED_COLUMNS)} required columns.")


def load_questions(csv_path='questions.csv'):
    """Loads and validates the questions CSV file."""
    print("Loading questions from CSV...")
    df = pd.read_csv(csv_path, header=0)
    validate_input_csv(df)
    
    # Remove empty rows (rows where ID or Question is NaN)
    df = df.dropna(subset=['Question', 'Correct Answer'])
    print(f"Loaded {len(df)} valid questions from CSV.\n")
    return df


def extract_answer(text):
    """Extracts the answer from the text using Regular Expression."""
    match = ANSWER_PATTERN.search(text)
    if match:
        return match.group(1).upper()
    return None


def stop_model(model_name):
    """Forcefully unloads the model from Ollama memory via CLI."""
    try:
        subprocess.run(["ollama", "stop", model_name], check=True, capture_output=True)
        print(f"--- Model {model_name} forcefully unloaded ---")
    except subprocess.CalledProcessError as e:
        print(f"--- Failed to stop model {model_name}: {e} ---")


def run_model_on_questions(model_name, df_questions, system_prompt, category_col='Time period'):
    """
    Runs a model on a set of questions and collects results.

    Args:
        model_name: Name of the Ollama model to test
        df_questions: DataFrame with questions (already validated and filtered)
        system_prompt: System message for the model

    Returns:
        List of result dictionaries
    """
    results = []

    print(f"\n>>> Starting benchmark for model: {model_name}")
    print(f">>> Total questions to process: {len(df_questions)}")

    for index, row in df_questions.iterrows():
        prompt = f"""
        Питання: {row['Question']}
        Варіанти:
        A) {row['Choice A']}
        B) {row['Choice B']}
        C) {row['Choice C']}
        D) {row['Choice D']}

        Твоя відповідь:
        """

        try:
            # Model call (stateless, temperature=0 for determinism)
            response = ollama.generate(
                model=model_name,
                system=system_prompt,
                prompt=prompt,
                options={
                    'temperature': 0,   # For deterministic output
                    'top_k': 1          # Greediest sampling
                }
            )

            thinking = response.get('thinking', None)
            raw_response = response.get('response', '')
            answer = extract_answer(raw_response)

            question_id = row['ID'] if not pd.isna(row['ID']) else f"q_{index:05d}"
            actual_answer = str(row['Correct Answer']).strip().upper()
            is_correct = (answer == actual_answer) if answer else False

            # Build result row matching OUTPUT_CSV_COLUMNS structure
            results.append({
                'id': question_id,
                'model': model_name,
                'category': row[category_col],
                'raw_response': raw_response.strip() or 'N/A',
                'thinking': thinking or 'N/A',
                'predicted': answer or 'N/A',
                'actual': actual_answer,
                'is_correct': is_correct
            })

            print(f"[{model_name}] Question {question_id}. Answer: {answer}. Correct: {actual_answer}")

        except Exception as e:
            print(f"Error while running {model_name}: {e}")

    return results


def visualize_answer_distribution(df, output_path='answer_distribution.png'):
    """
    Visualizes the distribution of correct answers (A, B, C, D) in the dataset.
    
    Args:
        df: DataFrame with 'Correct Answer' column
        output_path: Path where to save the chart
    """
    import matplotlib.pyplot as plt
    import seaborn as sns
    
    # Count occurrences of each answer
    answer_counts = df['Correct Answer'].value_counts().sort_index()
    
    # Print statistics
    print("\n--- Answer Distribution in Dataset ---")
    print(answer_counts)
    print(f"\nTotal questions: {answer_counts.sum()}")
    print("\nPercentages:")
    percentages = (answer_counts / answer_counts.sum() * 100).round(2)
    for answer, pct in percentages.items():
        print(f"  {answer}: {pct}%")
    
    # Create bar chart
    plt.figure(figsize=(10, 6))
    sns.set_theme(style="whitegrid")
    
    colors = ['#1f77b4', '#ff7f0e', '#2ca02c', '#d62728']  # Blue, Orange, Green, Red
    plot = plt.bar(answer_counts.index, answer_counts.values, color=colors[:len(answer_counts)])
    
    plt.title('Distribution of Correct Answers in Dataset', fontsize=16, pad=20)
    plt.ylabel('Number of Questions', fontsize=12)
    plt.xlabel('Correct Answer', fontsize=12)
    plt.xticks(fontsize=11)
    plt.yticks(fontsize=11)
    
    # Add value labels on top of bars
    for i, (answer, count) in enumerate(answer_counts.items()):
        percentage = percentages[answer]
        plt.text(i, count, f'{count}\n({percentage}%)', 
                ha='center', va='bottom', fontsize=10, fontweight='bold')
    
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close()
    print(f"\n--- Answer distribution chart saved to {output_path} ---")


def check_answers_distribution():
    """Analyzes and visualizes the distribution of correct answers in the dataset."""
    df = pd.read_csv('questions.csv', header=0)
    
    # Remove empty rows
    df = df.dropna(subset=['ID', 'Question', 'Correct Answer'])
    
    # Visualize answer distribution
    visualize_answer_distribution(df, output_path='answer_distribution.png')
